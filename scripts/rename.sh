#!/usr/bin/env bash
set -euo pipefail

# Always operate from the repo root, regardless of where this is invoked from.
cd "$(dirname "${BASH_SOURCE[0]}")/.."

DEFAULT_NAME="my-app"
TEMPLATE_URL="https://github.com/Napam/backwerust-template"
SENTINEL="__BACKWERUST_TEMPLATE_URL__"

echo "╔══════════════════════════════════════╗"
echo "║      Backwerust Template Renamer     ║"
echo "╚══════════════════════════════════════╝"
echo ""

# Refuse to mix the rename with uncommitted work: git checkout . would throw
# that work away too.
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    UNDO="git checkout ."
    if ! git diff --quiet || ! git diff --cached --quiet; then
        echo "Working tree has uncommitted changes." >&2
        echo "Commit or stash them before renaming." >&2
        exit 1
    fi
    # git checkout . leaves untracked files in place, but the scan below still
    # rewrites them, so a half-applied rename could not be undone.
    UNTRACKED=$(git ls-files --others --exclude-standard)
    if [[ -n "$UNTRACKED" ]]; then
        COUNT=$(printf '%s\n' "$UNTRACKED" | wc -l | tr -d '[:space:]')
        echo "Working tree has $COUNT untracked file(s):" >&2
        printf '%s\n' "$UNTRACKED" | sed -n '1,10p' >&2
        echo "Commit, stash, or remove them before renaming." >&2
        exit 1
    fi
else
    UNDO="restore from your backup"
fi

echo "Accepts a kebab-case project name, for example my-app."
read -r -p "Project name: " NAME
NAME="${NAME:-$DEFAULT_NAME}"
KEBAB=$(printf '%s' "$NAME" | tr '[:upper:]' '[:lower:]' | tr '_' '-')

if [[ ! "$KEBAB" =~ ^[a-z][a-z0-9]*(-[a-z0-9]+)*$ ]]; then
    echo "Use lowercase letters, digits and single hyphens, starting with a letter." >&2
    exit 1
fi

SNAKE="${KEBAB//-/_}"
DEFAULT_DISPLAY=$(printf '%s' "$KEBAB" | tr '-' ' ' | awk '{
    for (i = 1; i <= NF; i++) $i = toupper(substr($i, 1, 1)) substr($i, 2)
    print
}')

read -r -p "Display name (e.g. $DEFAULT_DISPLAY): " DISPLAY
DISPLAY="${DISPLAY:-$DEFAULT_DISPLAY}"

echo ""
echo "══════════════════════════════════════"
echo "  Will replace:"
echo "    backwerust-template  -> $KEBAB"
echo "    backwerust_template  -> $SNAKE"
echo "    backwerust           -> $KEBAB"
echo "    Backwerust Template  -> $DISPLAY"
echo "══════════════════════════════════════"
echo ""
echo "This is a one-way operation. Undo with: $UNDO"
echo ""
read -r -p "Continue? [y/N] " CONFIRM
if [[ ! "$CONFIRM" =~ ^[Yy]$ ]]; then
    echo "Aborted."
    exit 0
fi

echo ""
echo "Replacing..."

# Escape a string for use as the replacement text in sed s|||.
esc() {
    printf '%s' "$1" | sed 's/[\\&|]/\\&/g'
}

# GNU sed and BSD sed disagree on in-place editing: GNU takes -i with an
# optional attached suffix, BSD requires the suffix as a separate argument.
if sed --version >/dev/null 2>&1; then
    sedi() { sed -i "$@"; }    # GNU
else
    sedi() { sed -i '' "$@"; } # BSD/macOS
fi

K=$(esc "$KEBAB")
S=$(esc "$SNAKE")
D=$(esc "$DISPLAY")
U=$(esc "$TEMPLATE_URL")

# Source and config files only. Lockfiles are regenerated by cargo; build
# output and dependencies are left alone.
FILES=$(find . -type f \
    \( -name '*.rs' -o -name '*.toml' -o -name '*.yml' -o -name '*.yaml' \
     -o -name '*.md' -o -name '*.ts' -o -name '*.json' -o -name '*.css' \
     -o -name 'Dockerfile*' -o -name '.gitignore' -o -name '.dockerignore' \) \
    -not -path './.git/*' \
    -not -path './target/*' \
    -not -path './web/node_modules/*' \
    -not -path './web/tmp/*' \
    -not -path './web/static/*' \
    -not -path './tmp/*' \
    -not -path './bin/*' \
    -not -path './data/*' \
    -not -path './plans/*' \
    -not -name 'Cargo.lock' \
    -not -name 'bun.lock' \
    -not -name 'bun.lockb' \
    -not -name 'package-lock.json' \
    -not -name 'pnpm-lock.yaml' \
    -not -name 'rename.sh')

# Order matters: replace the underscore and hyphen forms before the bare
# package/binary name. The sentinel keeps the template clone URL in README.md
# pointing at the template instead of the new project.
while IFS= read -r f; do
    [[ -z "$f" ]] && continue
    sedi "s|$U|$SENTINEL|g" "$f"
    sedi "s|backwerust_template|$S|g" "$f"
    sedi "s|backwerust-template|$K|g" "$f"
    sedi "s|Backwerust Template|$D|g" "$f"
    sedi "s|backwerust|$K|g" "$f"
    sedi "s|$SENTINEL|$U|g" "$f"
done <<< "$FILES"

echo ""
echo "Installing, formatting, and checking..."
task init
task fix
task check

echo ""
echo "Renamed to $DISPLAY ($KEBAB)."
echo "Start the dev server with: task dev"
